"""Write members into the open Blender scene. The only module that imports bpy.

Everything written here is generated output. Each object is flagged
`bower_generated` and is rebuilt in place from source on the next run, at an
identity transform so that its data coordinates are world metres. Objects
without that flag are never modified.
"""
from __future__ import annotations

from math import radians

import bmesh
import bpy
from mathutils import Matrix

from .centreline import norm, sub
from .member import Member, diagnostics, sweep

ROOT_COLLECTION = "BOWER_V1"
CENTRELINE_COLLECTION = {
    "primary": "20_PRIMARY_CENTERLINES",
    "secondary": "30_SECONDARY_CENTERLINES",
    "cable": "40_CABLES",
}
MESH_COLLECTION = {
    "primary": "21_PRIMARY_MESHES",
    "secondary": "31_SECONDARY_MESHES",
    "cable": "40_CABLES",
}
TIMBER_MATERIAL = ("BOWER_timber_preview", (0.72, 0.52, 0.30, 1.0))


def _collection(scene, name: str):
    root = bpy.data.collections.get(ROOT_COLLECTION) or bpy.data.collections.new(ROOT_COLLECTION)
    if root.name not in scene.collection.children:
        scene.collection.children.link(root)
    collection = bpy.data.collections.get(name) or bpy.data.collections.new(name)
    if collection.name not in root.children:
        root.children.link(collection)
    return collection


def _place(name: str, data, collection, props: dict):
    """Create object `name`, or swap freshly built data into the one generated earlier."""
    obj = bpy.data.objects.get(name)
    if obj is None:
        obj = bpy.data.objects.new(name, data)
    elif not obj.get("bower_generated"):
        raise RuntimeError(f"object {name!r} exists and was not generated by bower; refusing to overwrite it")
    else:
        old = obj.data
        obj.data = data
        if old.users == 0:
            bpy.data.batch_remove([old])
    data.name = name
    for other in obj.users_collection:
        if other != collection:
            other.objects.unlink(obj)
    if obj.name not in collection.objects:
        collection.objects.link(obj)
    obj.matrix_world = Matrix.Identity(4)
    obj["bower_generated"] = True
    for key, value in props.items():
        obj[key] = value
    return obj


def _curve_data(member: Member, resolution_u: int):
    curve = bpy.data.curves.new(member.id, "CURVE")
    curve.dimensions = "3D"
    curve.resolution_u = resolution_u
    spline = curve.splines.new("BEZIER")
    spline.bezier_points.add(len(member.path.anchors) - 1)
    for point, anchor in zip(spline.bezier_points, member.path.anchors):
        point.handle_left_type = point.handle_right_type = "FREE"
        point.co = anchor.co
        point.handle_left = anchor.handle_left
        point.handle_right = anchor.handle_right
    return curve


def _material():
    name, colour = TIMBER_MATERIAL
    material = bpy.data.materials.get(name)
    if material is None:
        material = bpy.data.materials.new(name)
        material.diffuse_color = colour
    return material


def _mesh_data(member: Member, stations):
    verts, faces = sweep(member, stations)
    mesh = bpy.data.meshes.new(member.id)
    mesh.from_pydata(verts, [], faces)
    mesh.update()
    mesh.shade_smooth()
    mesh.set_sharp_from_angle(angle=radians(30))
    mesh.materials.append(_material())
    return mesh


def _centreline_deviation(member: Member, obj, resolution_u: int) -> dict:
    """Compare the curve as Blender evaluates it with the same samples computed from source."""
    evaluated = obj.evaluated_get(bpy.context.evaluated_depsgraph_get())
    mesh = evaluated.to_mesh()
    scene_points = [tuple(evaluated.matrix_world @ v.co) for v in mesh.vertices]
    evaluated.to_mesh_clear()
    source_points = member.path.points_uniform_parameter(resolution_u)
    check = {"scene_points": len(scene_points), "source_points": len(source_points), "max_deviation_m": None}
    if len(scene_points) == len(source_points):
        check["max_deviation_m"] = max(norm(sub(a, b)) for a, b in zip(scene_points, source_points))
    return check


def _mesh_check(member: Member, obj) -> dict:
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    check = {
        "vertices": len(bm.verts),
        "faces": len(bm.faces),
        "closed_manifold": all(e.is_manifold for e in bm.edges),
        "volume_m3": round(bm.calc_volume(signed=True), 6),
        "section_x_length_m3": round(member.width * member.depth * member.path.length, 6),
    }
    bm.free()
    return check


def build_member(scene, member: Member, sampling: dict) -> dict:
    """Write one member as a centreline curve plus a separate swept mesh; return its report."""
    props = {
        "bower_id": member.id,
        "bower_role": member.role,
        "bower_width_m": member.width,
        "bower_depth_m": member.depth,
    }
    resolution_u = sampling["curve_resolution_u"]
    centreline = _place(
        f"CL_{member.id}",
        _curve_data(member, resolution_u),
        _collection(scene, CENTRELINE_COLLECTION[member.role]),
        {**props, "bower_kind": "centreline"},
    )
    centreline.show_in_front = True  # keep the centreline readable through its own timber
    stations = member.path.stations(sampling["mesh_station_spacing_m"])
    timber = _place(
        f"TM_{member.id}",
        _mesh_data(member, stations),
        _collection(scene, MESH_COLLECTION[member.role]),
        {**props, "bower_kind": "timber_preview", "bower_centreline": centreline.name},
    )
    bpy.context.view_layer.update()
    report = diagnostics(member, sampling["export_station_spacing_m"])
    report["objects"] = {"centreline": centreline.name, "timber": timber.name}
    report["centreline_check"] = _centreline_deviation(member, centreline, resolution_u)
    report["mesh_check"] = _mesh_check(member, timber)
    return report

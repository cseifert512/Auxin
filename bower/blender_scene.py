"""Write the design into the open Blender scene. The only module that imports bpy.

Everything written here is generated output. Each object is flagged
`bower_generated` and is rebuilt in place from source on the next run, at an
identity transform so that its data coordinates are world metres. Objects
without that flag are never modified.

Handles are the one kind of generated object meant to be moved by hand: each
remembers where it was placed, and `read_dragged_handles` turns any that have
since moved into the same topology operations a script would call.
"""
from __future__ import annotations

from math import cos, pi, radians, sin
from pathlib import Path

import bmesh
import bpy
from mathutils import Matrix, Vector

from . import topology
from .centreline import norm, sub
from .envelope import CREASE_KINDS, build_envelope, check_envelope
from .member import Member, diagnostics, sweep

ROOT_COLLECTION = "BOWER_V1"
CONTROLS, ENVELOPES, CONTEXT, CAMERAS = "00_CONTROLS", "10_ENVELOPES", "60_CONTEXT", "70_CAMERAS"
CENTRELINE_COLLECTION = {
    "primary": "20_PRIMARY_CENTERLINES",
    "secondary": "30_SECONDARY_CENTERLINES",
    "cable": "40_CABLES",
}
MESH_COLLECTION = {
    "primary": "21_PRIMARY_MESHES",
    "secondary": "31_SECONDARY_MESHES",
    "cable": "40_CABLES",
}
# Flat viewport colours that tell the layers apart; not materials in any finished sense.
COLOURS = {
    "timber": (0.72, 0.52, 0.30, 1.0),
    "envelope": (0.87, 0.85, 0.80, 1.0),
    "arch": (0.05, 0.05, 0.05, 1.0),
    "pier": (0.05, 0.05, 0.05, 1.0),
    "eave": (0.10, 0.50, 0.32, 1.0),
    "crown": (0.05, 0.05, 0.05, 1.0),
    "groin": (0.10, 0.32, 0.70, 1.0),
    "ridge": (0.85, 0.36, 0.08, 1.0),
    "ground": (0.60, 0.64, 0.56, 1.0),
    "figure": (0.22, 0.22, 0.25, 1.0),
}
GUIDE_RADIUS_M = 0.025  # boundary curves are drawn as thin tubes so that they show in renders
HANDLE_DISPLAY = {"pier": ("CUBE", 0.22), "apex": ("SPHERE", 0.18), "crown": ("SPHERE", 0.30)}


# --- shared helpers -------------------------------------------------------------


def _collection(scene, name: str):
    root = bpy.data.collections.get(ROOT_COLLECTION) or bpy.data.collections.new(ROOT_COLLECTION)
    if root.name not in scene.collection.children:
        scene.collection.children.link(root)
    collection = bpy.data.collections.get(name) or bpy.data.collections.new(name)
    if collection.name not in root.children:
        root.children.link(collection)
    return collection


def _place(name: str, data, collection, props: dict):
    """Create object `name`, or swap freshly built data into the one generated earlier.

    `data` is None for empties.
    """
    obj = bpy.data.objects.get(name)
    if obj is None:
        obj = bpy.data.objects.new(name, data)
    elif not obj.get("bower_generated"):
        raise RuntimeError(f"object {name!r} exists and was not generated by bower; refusing to overwrite it")
    elif data is not None:
        old = obj.data
        obj.data = data
        if old.users == 0:
            bpy.data.batch_remove([old])
    if data is not None:
        data.name = name
    for other in obj.users_collection:
        if other != collection:
            other.objects.unlink(obj)
    if obj.name not in collection.objects:
        collection.objects.link(obj)
    obj.matrix_world = Matrix.Identity(4)
    obj["bower_generated"] = True
    for key, value in props.items():
        obj[key] = value
    return obj


def _remove_stale(keep: set, **tags) -> int:
    """Remove generated objects carrying `tags` that the current build did not produce."""
    stale = [
        o
        for o in bpy.data.objects
        if o.get("bower_generated") and o.name not in keep and all(o.get(k) == v for k, v in tags.items())
    ]
    data = {o.data for o in stale if o.data is not None}
    for obj in stale:
        bpy.data.objects.remove(obj, do_unlink=True)
    orphans = [d for d in data if d.users == 0]
    if orphans:
        bpy.data.batch_remove(orphans)
    return len(stale)


def _material(key: str):
    name = f"BOWER_{key}"
    material = bpy.data.materials.get(name)
    if material is None:
        material = bpy.data.materials.new(name)
        material.diffuse_color = COLOURS[key]
    return material


def _curve_data(name: str, paths, resolution_u: int, tube_radius: float = 0.0):
    """A curve data-block with one Bezier spline per path, exactly as the paths define them."""
    curve = bpy.data.curves.new(name, "CURVE")
    curve.dimensions = "3D"
    curve.resolution_u = resolution_u
    curve.bevel_depth = tube_radius
    curve.bevel_resolution = 2
    for path in paths:
        spline = curve.splines.new("BEZIER")
        spline.bezier_points.add(len(path.anchors) - 1)
        for point, anchor in zip(spline.bezier_points, path.anchors):
            point.handle_left_type = point.handle_right_type = "FREE"
            point.co = anchor.co
            point.handle_left = anchor.handle_left
            point.handle_right = anchor.handle_right
    return curve


def _prism(name: str, centre, radius: float, z0: float, z1: float, sides: int, material: str):
    """A closed vertical prism; with z0 == z1 it is a flat disc."""
    ring = [(centre[0] + radius * cos(2 * pi * k / sides), centre[1] + radius * sin(2 * pi * k / sides)) for k in range(sides)]
    mesh = bpy.data.meshes.new(name)
    if z0 == z1:
        mesh.from_pydata([(x, y, z0) for x, y in ring], [], [tuple(range(sides))])
    else:
        verts = [(x, y, z) for z in (z0, z1) for x, y in ring]
        sides_faces = [(k, (k + 1) % sides, sides + (k + 1) % sides, sides + k) for k in range(sides)]
        mesh.from_pydata(verts, [], sides_faces + [tuple(reversed(range(sides))), tuple(range(sides, 2 * sides))])
    mesh.update()
    mesh.materials.append(_material(material))
    return mesh


# --- Level C: members (Gate 0) ---------------------------------------------------


def _member_mesh(member: Member, stations):
    verts, faces = sweep(member, stations)
    mesh = bpy.data.meshes.new(member.id)
    mesh.from_pydata(verts, [], faces)
    mesh.update()
    mesh.shade_smooth()
    mesh.set_sharp_from_angle(angle=radians(30))
    mesh.materials.append(_material("timber"))
    return mesh


def _centreline_deviation(member: Member, obj, resolution_u: int) -> dict:
    """Compare the curve as Blender evaluates it with the same samples computed from source."""
    evaluated = obj.evaluated_get(bpy.context.evaluated_depsgraph_get())
    mesh = evaluated.to_mesh()
    scene_points = [tuple(evaluated.matrix_world @ v.co) for v in mesh.vertices]
    evaluated.to_mesh_clear()
    source_points = member.path.points_uniform_parameter(resolution_u)
    check = {"scene_points": len(scene_points), "source_points": len(source_points), "max_deviation_m": None}
    if len(scene_points) == len(source_points):
        check["max_deviation_m"] = max(norm(sub(a, b)) for a, b in zip(scene_points, source_points))
    return check


def _member_mesh_check(member: Member, obj) -> dict:
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    check = {
        "vertices": len(bm.verts),
        "faces": len(bm.faces),
        "closed_manifold": all(e.is_manifold for e in bm.edges),
        "volume_m3": round(bm.calc_volume(signed=True), 6),
        "section_x_length_m3": round(member.width * member.depth * member.path.length, 6),
    }
    bm.free()
    return check


def build_member(scene, member: Member, sampling: dict) -> dict:
    """Write one member as a centreline curve plus a separate swept mesh; return its report."""
    props = {
        "bower_id": member.id,
        "bower_role": member.role,
        "bower_width_m": member.width,
        "bower_depth_m": member.depth,
    }
    resolution_u = sampling["curve_resolution_u"]
    centreline = _place(
        f"CL_{member.id}",
        _curve_data(member.id, [member.path], resolution_u),
        _collection(scene, CENTRELINE_COLLECTION[member.role]),
        {**props, "bower_kind": "centreline"},
    )
    centreline.show_in_front = True  # keep the centreline readable through its own timber
    stations = member.path.stations(sampling["mesh_station_spacing_m"])
    timber = _place(
        f"TM_{member.id}",
        _member_mesh(member, stations),
        _collection(scene, MESH_COLLECTION[member.role]),
        {**props, "bower_kind": "timber_preview", "bower_centreline": centreline.name},
    )
    bpy.context.view_layer.update()
    report = diagnostics(member, sampling["export_station_spacing_m"])
    report["objects"] = {"centreline": centreline.name, "timber": timber.name}
    report["centreline_check"] = _centreline_deviation(member, centreline, resolution_u)
    report["mesh_check"] = _member_mesh_check(member, timber)
    return report


# --- Levels A and B: handles and envelope (Gate 1) -------------------------------


def _envelope_mesh(env):
    """One welded mesh for the room: smooth inside each patch, creased along groins, ridges and
    eaves, with each face tagged by the patch (and so the bay) it belongs to."""
    mesh = bpy.data.meshes.new(env.room_id)
    mesh.from_pydata(env.verts, [], env.faces)
    mesh.update(calc_edges=True)
    mesh.shade_smooth()
    creases = {
        frozenset(pair)
        for edge in env.edges.values()
        if edge.kind in CREASE_KINDS
        for pair in zip(env.edge_verts[edge.id], env.edge_verts[edge.id][1:])
    }
    for edge in mesh.edges:
        if frozenset(edge.vertices) in creases:
            edge.use_edge_sharp = True
    patch_index = {patch_id: i for i, patch_id in enumerate(env.patches)}
    tags = mesh.attributes.new("bower_patch", "INT", "FACE")
    tags.data.foreach_set("value", [patch_index[p] for p in env.face_patch])
    mesh.materials.append(_material("envelope"))
    return mesh


def _envelope_scene_check(env, obj) -> dict:
    """What Blender holds, measured in Blender, against what the source computed."""
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    check = {
        "vertices": len(bm.verts),
        "faces": len(bm.faces),
        "rim_edges": sum(e.is_boundary for e in bm.edges),
        "non_manifold_edges": sum(not e.is_manifold and not e.is_boundary for e in bm.edges),
        "sharp_edges": sum(not e.smooth for e in bm.edges),
        "max_vertex_deviation_m": max(norm(sub(tuple(v.co), p)) for v, p in zip(bm.verts, env.verts)),
    }
    bm.free()
    return check


def _handle(scene, kind: str, element_id: str, location, tags: dict):
    display, size = HANDLE_DISPLAY[kind]
    name = f"H_{element_id}" + {"pier": "", "apex": ".apex", "crown": ".crown"}[kind]
    obj = _place(
        name,
        None,
        _collection(scene, CONTROLS),
        {**tags, "bower_kind": "handle", "bower_handle": kind, "bower_id": element_id, "bower_placed_at": list(location)},
    )
    obj.location = location
    obj.empty_display_type, obj.empty_display_size = display, size
    obj.show_name = obj.show_in_front = True
    obj.lock_location[2] = kind == "pier"  # piers stay on the floor
    obj.lock_rotation = obj.lock_scale = (True, True, True)
    return obj


def build_room(scene, design: dict, room: dict) -> dict:
    """Write one room: its handles, its named boundary curves and its envelope mesh."""
    rid, z0 = room["id"], room["floor_z_m"]
    tags = {"bower_room": rid}
    env = build_envelope(room, design["sampling"])
    envelope_check = check_envelope(env)
    if not envelope_check["ok"]:  # refuse before touching the scene
        raise topology.DesignError(f"{rid}: this design gives an invalid envelope: " + "; ".join(envelope_check["problems"]))
    envelopes, controls = _collection(scene, ENVELOPES), _collection(scene, CONTROLS)
    built = []

    surface = _place(f"ENV_{rid}", _envelope_mesh(env), envelopes, {**tags, "bower_kind": "envelope", "bower_patches": ",".join(env.patches)})
    built.append(surface)

    guides = {}  # one curve object per shaft, groin, arch, eave and ridge, and one for the crown ring
    for edge in env.edges.values():
        if edge.kind == "crown":
            key = f"{rid}.crown"
        elif edge.kind in ("arch", "eave", "groin"):
            key = edge.id.rsplit(".", 1)[0]  # the .L/.R or .lower/.upper parts share one object
        else:
            key = edge.id
        guides.setdefault(key, (edge.kind, []))[1].append(edge.path)
    for key, (kind, paths) in guides.items():
        curve = _curve_data(key, paths, design["sampling"]["curve_resolution_u"], GUIDE_RADIUS_M)
        curve.materials.append(_material(kind))
        built.append(_place(f"G_{key}", curve, envelopes, {**tags, "bower_kind": "guide", "bower_id": key}))

    footprint = bpy.data.curves.new(f"{rid}.footprint", "CURVE")
    footprint.dimensions = "3D"
    ring = footprint.splines.new("POLY")
    ring.points.add(len(room["piers"]) - 1)
    for point, pier in zip(ring.points, room["piers"]):
        point.co = (*pier["position_m"], z0, 1.0)
    ring.use_cyclic_u = True
    built.append(_place(f"CTRL_{rid}.footprint", footprint, controls, {**tags, "bower_kind": "control_polygon"}))

    for pier in room["piers"]:
        built.append(_handle(scene, "pier", pier["id"], (*pier["position_m"], z0), tags))
    for bay in room["bays"]:
        built.append(_handle(scene, "apex", bay["id"], topology.apex_point(room, bay), tags))
    crown = room["crown"]
    built.append(_handle(scene, "crown", rid, (*crown["centre_m"], z0 + crown["height_m"]), tags))

    removed = _remove_stale({o.name for o in built}, bower_room=rid)
    bpy.context.view_layer.update()
    return {
        "room": rid,
        "piers": [p["id"] for p in room["piers"]],
        "bays": [b["id"] for b in room["bays"]],
        "objects": len(built),
        "stale_objects_removed": removed,
        "envelope": envelope_check,
        "scene_check": _envelope_scene_check(env, surface),
    }


def read_dragged_handles(design: dict) -> tuple[dict, list]:
    """Fold handles that have been moved since they were placed back into the design.

    Returns the new design and the change records. Piers and crowns are read
    first so that a dragged apex is measured against its chord as it now stands.
    """
    moved = {}
    for obj in bpy.data.objects:
        if obj.get("bower_kind") == "handle" and (obj.location - Vector(obj["bower_placed_at"])).length > 1e-5:
            moved.setdefault(obj["bower_handle"], []).append((obj["bower_id"], tuple(obj.location)))
    changes = []
    for element_id, p in sorted(moved.get("pier", [])):
        design, change = topology.move_pier(design, element_id, p[:2])
        changes.append(change)
    for element_id, p in sorted(moved.get("crown", [])):
        floor = topology.get_room(design, element_id)["floor_z_m"]
        design, change = topology.set_crown(design, element_id, centre_m=p[:2], height_m=p[2] - floor)
        changes.append(change)
    for element_id, p in sorted(moved.get("apex", [])):
        params = topology.apex_params(*topology.find(design, "bays", element_id), p)
        design, change = topology.set_apex(
            design, element_id, height_m=params["apex_height_m"], shift=params["apex_shift"], out_m=params["apex_out_m"]
        )
        changes.append(change)
    return design, changes


# --- context and views -----------------------------------------------------------


def build_context(scene, design: dict) -> None:
    """A ground disc and a figure for scale. Neither is architecture."""
    context, collection = design["context"], _collection(scene, CONTEXT)
    ground = _prism("ground", (0.0, 0.0), context["ground_radius_m"], -0.02, -0.02, 96, "ground")
    figure = context["scale_figure"]
    person = _prism("scale_figure", figure["position_m"], 0.22, 0.0, figure["height_m"], 8, "figure")
    built = [
        _place("CTX_ground", ground, collection, {"bower_kind": "context"}),
        _place("CTX_scale_figure", person, collection, {"bower_kind": "context"}),
    ]
    _remove_stale({o.name for o in built}, bower_kind="context")


def build_views(scene, design: dict) -> None:
    """One camera per entry in design["views"]."""
    collection = _collection(scene, CAMERAS)
    built = []
    for view in design["views"]:
        camera = bpy.data.cameras.new(view["id"])
        camera.clip_end = 500.0
        if view["projection"] == "ortho":
            camera.type, camera.ortho_scale = "ORTHO", view["ortho_scale_m"]
        else:
            camera.lens = view["lens_mm"]
        obj = _place(f"CAM_{view['id']}", camera, collection, {"bower_kind": "view", "bower_id": view["id"]})
        obj.location = view["location_m"]
        look = Vector(view["target_m"]) - Vector(view["location_m"])
        if look.xy.length > 1e-9:  # straight down keeps the identity rotation, which is north-up
            obj.rotation_euler = look.to_track_quat("-Z", "Y").to_euler()
        built.append(obj)
    _remove_stale({o.name for o in built}, bower_kind="view")


def render_views(scene, design: dict, out_dir, prefix: str = "", only=None, size=(1600, 1000)) -> list[str]:
    """Render the design's views with the Workbench engine, then put the render settings back."""
    render, shading, world = scene.render, scene.display.shading, scene.world
    saved = (render.engine, scene.camera, render.resolution_x, render.resolution_y, render.resolution_percentage, render.filepath)
    saved_world = tuple(world.color) if world else None
    paths = []
    try:
        render.engine = "BLENDER_WORKBENCH"
        render.resolution_x, render.resolution_y = size
        render.resolution_percentage = 100
        shading.light, shading.color_type = "STUDIO", "MATERIAL"
        shading.show_cavity = shading.show_object_outline = True
        shading.show_shadows = False  # Workbench shadows misbehave on open surfaces
        if world:
            world.color = (0.80, 0.83, 0.86)
        for view in design["views"]:
            if only and view["id"] not in only:
                continue
            scene.camera = bpy.data.objects[f"CAM_{view['id']}"]
            render.filepath = str(Path(out_dir) / f"{prefix}{view['id']}.png")
            bpy.ops.render.render(write_still=True)
            paths.append(render.filepath)
    finally:
        render.engine, scene.camera, render.resolution_x, render.resolution_y, render.resolution_percentage, render.filepath = saved
        if world:
            world.color = saved_world
    return paths


def build_design(scene, design: dict) -> dict:
    """Rebuild every generated object for the design: rooms, context and view cameras."""
    topology.validate(design)
    report = {"rooms": [build_room(scene, design, room) for room in design["rooms"]]}
    build_context(scene, design)
    build_views(scene, design)
    bpy.context.view_layer.update()
    return report
